// The tables other than English load only when picked, so an English
// interface never fetches them. Until one arrives, t() reads English.
/** @type {Record<string, () => Promise<Record<string, string>>>} */
const LOADERS = { nb: () => import('./i18n-nb.js').then(m => m.NB) };

/** @type {Record<string, Record<string, string>>} */
const TABLES = { en: STRINGS };

// The languages the setting offers, each named in itself so a reader finds
// their own whatever the UI is in now.
export const LANGUAGES = /** @type {[string, string][]} */ ([['en', 'English'], ['nb', 'Norsk bokmål']]);

let active = 'en';

// The table code for a BCP 47 tag such as navigator.language. Nynorsk and
// the bare `no` read bokmål before English; anything unknown reads English.
/** @param {string | null | undefined} tag */
export function matchLanguage(tag) {
  const primary = String(tag || '').toLowerCase().split(/[-_]/)[0];
  if (primary === 'en' || primary in LOADERS) return primary;
  if (primary === 'no' || primary === 'nn') return 'nb';
  return 'en';
}

// Fetches a language's table once. A table that fails to load leaves t()
// on English, and the next call tries again.
/** @param {string} code @returns {Promise<void>} */
export function loadLanguage(code) {
  const lang = matchLanguage(code);
  if (lang in TABLES) return Promise.resolve();
  return LOADERS[lang]().then(table => { TABLES[lang] = table; });
}

// Resolves once the language's table is in, so text drawn after reads it.
/** @param {string} code @returns {Promise<void>} */
export function setLanguage(code) {
  const lang = matchLanguage(code);
  const loaded = loadLanguage(lang).catch(() => {});
  return loaded.then(() => {
    active = lang;
    if (typeof document !== 'undefined') document.documentElement.lang = active;
  });
}

// The active language, which is also the locale numbers and sorting use.
// Dates are not formatted by it: they are stored and shown as ISO 8601
// (2026-11-08) in every language, which reads the same in both.
export function language() { return active; }

/** @param {string} k */
function lookup(k) {
  const table = TABLES[active];
  if (table && k in table) return table[k];
  return k in STRINGS ? /** @type {Record<string, string>} */ (STRINGS)[k] : undefined;
}

// Splits a template at its {name} slots, so a slot can hold a vnode as well
// as text. A `count` var picks the .one or .other variant of the key.
/** @param {string} key @param {Record<string, unknown>} [vars] */
function parts(key, vars) {
  let k = key;
  if (vars && typeof vars.count === 'number') {
    const variant = key + (vars.count === 1 ? '.one' : '.other');
    if (lookup(variant) !== undefined) k = variant;
  }
  const template = lookup(k) ?? key;
  return template.split(/\{(\w+)\}/).map((piece, i) => {
    if (i % 2 === 0) return piece;
    return vars && piece in vars ? vars[piece] : '{' + piece + '}';
  }).filter(piece => piece !== '');
}

/** @param {string} key @param {Record<string, unknown>} [vars] */
export function t(key, vars) {
  return parts(key, vars).join('');
}

// Like t, but the vars may be vnodes: returns the pieces for a template to
// render, for text that wraps a part of itself in an element.
/** @param {string} key @param {Record<string, unknown>} [vars] */
export function tx(key, vars) {
  return parts(key, vars);
}

export const stringKeys = () => Object.keys(STRINGS);

